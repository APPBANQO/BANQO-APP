create or replace function public.staff_list_questions(p_search text default '',p_status text default '',p_limit integer default 120,p_explanation_source text default '')
returns setof public.questions language plpgsql stable security definer set search_path=public as $$
begin
  if not public.is_staff() then raise exception 'No autorizado' using errcode='42501'; end if;
  return query select q.* from public.questions q
  where (coalesce(p_status,'')='' or q.status=p_status)
    and (coalesce(p_explanation_source,'')='' or q.explanation_source=p_explanation_source)
    and (coalesce(p_search,'')='' or q.external_id ilike '%'||p_search||'%' or q.stem ilike '%'||p_search||'%')
  order by q.updated_at desc limit least(greatest(coalesce(p_limit,120),1),500);
end; $$;
grant execute on function public.staff_list_questions(text,text,integer,text) to authenticated;

