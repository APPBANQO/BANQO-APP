returns jsonb language sql immutable as $$
  select to_jsonb(q)-array['correct_answer','explanation','galactic_tip','review_notes','created_by','updated_by','source_hash'];
$$;

create or replace function public.start_practice(
  p_count integer, p_mode text, p_filters jsonb default '{}'::jsonb, p_random boolean default true,
  p_question_ids uuid[] default null
) returns jsonb language plpgsql security definer set search_path=public as $$
declare uid uuid:=auth.uid(); ids uuid[]; sid uuid; qs jsonb; allowed integer; requested integer;
begin
  if uid is null then raise exception 'No autenticado'; end if;
  requested:=greatest(1,least(coalesce(p_count,15),100)); allowed:=public.free_questions_remaining();
  if allowed=0 then raise exception 'FREE_LIMIT_REACHED' using errcode='P0001'; end if;
  if allowed>=0 then requested:=least(requested,allowed); end if;
  if p_mode not in ('instant','exam') then p_mode:='instant'; end if;

  if p_question_ids is not null then
    select array_agg(x.id order by array_position(p_question_ids,x.id)) into ids from (
      select id from public.questions where id=any(p_question_ids) and status='PUBLICADA'
      order by array_position(p_question_ids,id) limit requested
    ) x;
  elsif p_random then
    select array_agg(id) into ids from (
      select id from public.questions q where q.status='PUBLICADA'
      and (coalesce(p_filters->>'exam','')='' or q.exam_type=p_filters->>'exam')
      and (coalesce(p_filters->>'bank','')='' or q.bank_name=p_filters->>'bank')
      and (coalesce(p_filters->>'specialty','')='' or q.specialty=p_filters->>'specialty')
      and (coalesce(p_filters->>'topic','')='' or q.topic=p_filters->>'topic')
      and (coalesce(p_filters->>'subtopic','')='' or q.subtopic=p_filters->>'subtopic')
      order by random() limit requested
    ) x;
  else
    select array_agg(id) into ids from (
      select id from public.questions q where q.status='PUBLICADA'
      and (coalesce(p_filters->>'exam','')='' or q.exam_type=p_filters->>'exam')
      and (coalesce(p_filters->>'bank','')='' or q.bank_name=p_filters->>'bank')
      and (coalesce(p_filters->>'specialty','')='' or q.specialty=p_filters->>'specialty')
      and (coalesce(p_filters->>'topic','')='' or q.topic=p_filters->>'topic')
      and (coalesce(p_filters->>'subtopic','')='' or q.subtopic=p_filters->>'subtopic')
      order by q.external_id limit requested
    ) x;
  end if;
  if coalesce(array_length(ids,1),0)=0 then raise exception 'NO_QUESTIONS' using errcode='P0001'; end if;
  insert into public.study_sessions(user_id,session_type,filters,question_ids)
  values(uid,'PRACTICE',coalesce(p_filters,'{}'::jsonb)||jsonb_build_object('answer_mode',p_mode),ids)
  returning id into sid;
  select jsonb_agg(public.safe_question(q) order by array_position(ids,q.id)) into qs
  from public.questions q where q.id=any(ids);
  return jsonb_build_object('session_id',sid,'questions',coalesce(qs,'[]'::jsonb),'allowed',allowed);
end; $$;
grant execute on function public.start_practice(integer,text,jsonb,boolean,uuid[]) to authenticated;

create or replace function public.start_simulation(p_sim uuid,p_mode text default 'exam')
returns jsonb language plpgsql security definer set search_path=public as $$
declare uid uuid:=auth.uid(); sim public.simulation_sets%rowtype; ids uuid[]; sid uuid; qs jsonb; allowed integer;
begin
  if uid is null then raise exception 'No autenticado'; end if;
  select * into sim from public.simulation_sets where id=p_sim and status='PUBLICADO';
  if sim.id is null then raise exception 'SIMULATION_NOT_AVAILABLE' using errcode='P0001'; end if;
  select array_agg(sq.question_id order by sq.order_no) into ids
  from public.simulation_questions sq join public.questions q on q.id=sq.question_id
  where sq.simulation_id=p_sim and not sq.is_reserve and q.status='PUBLICADA';
  if coalesce(array_length(ids,1),0)<>sim.question_count then raise exception 'SIMULATION_NOT_READY' using errcode='P0001'; end if;
  allowed:=public.free_questions_remaining();
  if allowed>=0 and allowed<array_length(ids,1) then raise exception 'FREE_SIMULATION_LIMIT' using errcode='P0001'; end if;
  if p_mode not in ('instant','exam') then p_mode:='exam'; end if;
  insert into public.study_sessions(user_id,session_type,simulation_id,filters,question_ids)
  values(uid,'SIMULATION',sim.id,jsonb_build_object('name',sim.name,'answer_mode',p_mode),ids) returning id into sid;
  select jsonb_agg(public.safe_question(q) order by array_position(ids,q.id)) into qs
  from public.questions q where q.id=any(ids);
  return jsonb_build_object('session_id',sid,'simulation',to_jsonb(sim),'questions',qs);
end; $$;
grant execute on function public.start_simulation(uuid,text) to authenticated;

create or replace function public.resume_study_session(p_session uuid)
returns jsonb language plpgsql security definer set search_path=public as $$
declare uid uuid:=auth.uid(); s public.study_sessions%rowtype; qs jsonb; ans jsonb; st jsonb;
begin
  select * into s from public.study_sessions where id=p_session and user_id=uid;
  if s.id is null then raise exception 'Sesión no encontrada'; end if;
  if s.status='COMPLETADA' then
    select jsonb_agg(((to_jsonb(q)-array['review_notes','source_hash','created_by','updated_by'])||jsonb_build_object('explanation',case when q.explanation_source='AUTO_LOCAL' then '' else q.explanation end,'galactic_tip',case when q.explanation_source='AUTO_LOCAL' then '' else q.galactic_tip end)) order by array_position(s.question_ids,q.id)) into qs from public.questions q where q.id=any(s.question_ids);
  else
    select jsonb_agg(public.safe_question(q) order by array_position(s.question_ids,q.id)) into qs from public.questions q where q.id=any(s.question_ids);
  end if;
  select coalesce(jsonb_object_agg(question_id::text,selected_answer) filter(where selected_answer is not null),'{}'::jsonb) into ans
  from public.attempts where session_id=s.id and user_id=uid;
  select coalesce(jsonb_object_agg(question_id::text,jsonb_build_object('marked',marked,'discarded',discarded_options)),'{}'::jsonb) into st
  from public.study_question_state where session_id=s.id and user_id=uid;
  return jsonb_build_object('session',to_jsonb(s),'questions',coalesce(qs,'[]'::jsonb),'answers',ans,'question_state',st);
end; $$;
grant execute on function public.resume_study_session(uuid) to authenticated;

create or replace function public.save_question_state(p_session uuid,p_question uuid,p_marked boolean,p_discarded text[])
returns void language plpgsql security definer set search_path=public as $$
declare uid uuid:=auth.uid();
begin
  if not exists(select 1 from public.study_sessions where id=p_session and user_id=uid and status='EN_CURSO' and p_question=any(question_ids))
    then raise exception 'Sesión no válida' using errcode='42501'; end if;
  insert into public.study_question_state(session_id,user_id,question_id,marked,discarded_options)
  values(p_session,uid,p_question,coalesce(p_marked,false),coalesce(p_discarded,'{}'::text[]))
  on conflict(session_id,question_id) do update set marked=excluded.marked,discarded_options=excluded.discarded_options,updated_at=now();
end; $$;
grant execute on function public.save_question_state(uuid,uuid,boolean,text[]) to authenticated;

create or replace function public.answer_question(
  p_session uuid,p_question uuid,p_letter text,p_marked boolean default false,
  p_discarded text[] default '{}'::text[],p_response_ms integer default null
) returns jsonb language plpgsql security definer set search_path=public as $$
declare uid uuid:=auth.uid(); s public.study_sessions%rowtype; q public.questions%rowtype; ok boolean; mode text; remaining integer;
begin
  if uid is null then raise exception 'No autenticado'; end if;
  perform pg_advisory_xact_lock(hashtext(uid::text));
  select * into s from public.study_sessions where id=p_session and user_id=uid and status='EN_CURSO' for update;
  if s.id is null or not p_question=any(s.question_ids) then raise exception 'Sesión no válida' using errcode='42501'; end if;
  if upper(p_letter) not in ('A','B','C','D','E') then raise exception 'Respuesta no válida'; end if;
  if not exists(select 1 from public.attempts where session_id=p_session and question_id=p_question and selected_answer is not null) then
    remaining:=public.free_questions_remaining();
    if remaining=0 then raise exception 'FREE_LIMIT_REACHED' using errcode='P0001'; end if;
  end if;
  select * into q from public.questions where id=p_question;
  ok:=upper(p_letter)=q.correct_answer; mode:=coalesce(s.filters->>'answer_mode','instant');
  insert into public.attempts(session_id,user_id,question_id,selected_answer,is_correct,marked,discarded_options,response_ms,answered_at)
  values(p_session,uid,p_question,upper(p_letter),ok,coalesce(p_marked,false),coalesce(p_discarded,'{}'::text[]),greatest(0,p_response_ms),now())
  on conflict(session_id,question_id) do update set selected_answer=excluded.selected_answer,is_correct=excluded.is_correct,
    marked=excluded.marked,discarded_options=excluded.discarded_options,response_ms=excluded.response_ms,answered_at=now();
  perform public.save_question_state(p_session,p_question,p_marked,p_discarded);
  if mode='instant' then
    return jsonb_build_object('ok',true,'is_correct',ok,'correct_answer',q.correct_answer,
      'explanation',case when q.explanation_source='AUTO_LOCAL' then '' else q.explanation end,
      'galactic_tip',case when q.explanation_source='AUTO_LOCAL' then '' else q.galactic_tip end);
  end if;
  return jsonb_build_object('ok',true);
end; $$;
grant execute on function public.answer_question(uuid,uuid,text,boolean,text[],integer) to authenticated;

create or replace function public.complete_study_session(p_session uuid,p_elapsed integer default 0)
returns jsonb language plpgsql security definer set search_path=public as $$
declare uid uuid:=auth.uid(); s public.study_sessions%rowtype; total integer; correct_n integer; incorrect_n integer; blank_n integer; score_n numeric; qs jsonb;
begin
  select * into s from public.study_sessions where id=p_session and user_id=uid for update;
  if s.id is null then raise exception 'Sesión no encontrada' using errcode='42501'; end if;
  total:=coalesce(array_length(s.question_ids,1),0);
  select count(*) filter(where is_correct is true),count(*) filter(where selected_answer is not null and is_correct is false)
    into correct_n,incorrect_n from public.attempts where session_id=s.id and user_id=uid;
  blank_n:=greatest(0,total-correct_n-incorrect_n); score_n:=case when total=0 then 0 else round(correct_n*100.0/total,2) end;
  update public.study_sessions set status='COMPLETADA',correct_count=correct_n,incorrect_count=incorrect_n,
    blank_count=blank_n,score=score_n,elapsed_seconds=greatest(0,p_elapsed),finished_at=coalesce(finished_at,now()) where id=s.id;
  select jsonb_agg(((to_jsonb(q)-array['review_notes','source_hash','created_by','updated_by'])||jsonb_build_object('explanation',case when q.explanation_source='AUTO_LOCAL' then '' else q.explanation end,
    'galactic_tip',case when q.explanation_source='AUTO_LOCAL' then '' else q.galactic_tip end)) order by array_position(s.question_ids,q.id))
    into qs from public.questions q where q.id=any(s.question_ids);
  return jsonb_build_object('correct',correct_n,'incorrect',incorrect_n,'blank',blank_n,'score',score_n,'questions',coalesce(qs,'[]'::jsonb));
end; $$;
grant execute on function public.complete_study_session(uuid,integer) to authenticated;

