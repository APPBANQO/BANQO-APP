create or replace function public.user_progress_summary()
returns jsonb language sql stable security definer set search_path=public as $$
  select jsonb_build_object(
    'total',count(a.id),
    'correct',count(a.id) filter(where a.is_correct is true),
    'sessions',(select count(*) from public.study_sessions sx where sx.user_id=auth.uid() and sx.status='COMPLETADA')
  )
  from public.attempts a join public.study_sessions s on s.id=a.session_id
  where a.user_id=auth.uid() and (s.status='COMPLETADA' or coalesce(s.filters->>'answer_mode','instant')='instant');
$$;
grant execute on function public.user_progress_summary() to authenticated;

create or replace function public.user_topic_progress()
returns table(specialty text,topic text,total bigint,correct bigint,accuracy_pct numeric)
language sql stable security definer set search_path=public as $$
  select q.specialty,q.topic,count(*),count(*) filter(where a.is_correct is true),
    round(100.0*count(*) filter(where a.is_correct is true)/nullif(count(*),0),1)
  from public.attempts a join public.study_sessions s on s.id=a.session_id join public.questions q on q.id=a.question_id
  where a.user_id=auth.uid() and (s.status='COMPLETADA' or coalesce(s.filters->>'answer_mode','instant')='instant')
  group by q.specialty,q.topic order by 5 asc nulls last;
$$;
grant execute on function public.user_topic_progress() to authenticated;

