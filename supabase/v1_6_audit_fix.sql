create or replace function public.user_attempt_history(p_limit integer default 1000)
returns table(question_id uuid,is_correct boolean,answered_at timestamptz,question jsonb)
language sql stable security definer set search_path=public as $$
  select a.question_id,a.is_correct,a.answered_at,
    (to_jsonb(q)-array['review_notes','source_hash','created_by','updated_by']) ||
    jsonb_build_object('explanation',case when q.explanation_source='AUTO_LOCAL' then '' else q.explanation end,
                       'galactic_tip',case when q.explanation_source='AUTO_LOCAL' then '' else q.galactic_tip end)
  from public.attempts a join public.study_sessions s on s.id=a.session_id left join public.questions q on q.id=a.question_id
  where a.user_id=auth.uid() and (s.status='COMPLETADA' or coalesce(s.filters->>'answer_mode','instant')='instant')
  order by a.answered_at desc limit least(greatest(coalesce(p_limit,1000),1),2000);
$$;
