create or replace function public.simulation_readiness(p_sim uuid)
returns jsonb language sql stable security definer set search_path=public as $$
  select jsonb_build_object(
    'total',count(*) filter(where not sq.is_reserve),
    'published',count(*) filter(where not sq.is_reserve and q.status='PUBLICADA'),
    'pending',count(*) filter(where not sq.is_reserve and q.status<>'PUBLICADA')
