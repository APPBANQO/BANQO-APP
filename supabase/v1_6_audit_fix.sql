create or replace function public.publish_simulation_questions(p_sim uuid)
returns integer language plpgsql security definer set search_path=public as $$
declare n integer;
begin
  if not public.is_admin() then raise exception 'No autorizado' using errcode='42501'; end if;
  update public.questions q set status='PUBLICADA',updated_by=auth.uid()
  from public.simulation_questions sq
  where sq.simulation_id=p_sim and sq.question_id=q.id and not sq.is_reserve
    and q.status in ('PENDIENTE','APROBADA');
  get diagnostics n=row_count; return n;
end; $$;
