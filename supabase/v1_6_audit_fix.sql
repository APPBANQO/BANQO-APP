-- Perfil: el alumno puede editar datos propios sin elevar rol, plan, XP o racha.
create or replace function public.protect_profile_privileges()
returns trigger language plpgsql set search_path=public as $$
begin
  if old.role='admin' and new.role<>'admin' and (select count(*) from public.profiles where role='admin')<=1 then
    raise exception 'No puedes quitar el rol al último administrador';
  end if;
  if auth.uid()=old.id and not public.is_admin() then
    new.role:=old.role; new.plan:=old.plan; new.xp:=old.xp; new.streak:=old.streak;
  end if;
  return new;
end; $$;
