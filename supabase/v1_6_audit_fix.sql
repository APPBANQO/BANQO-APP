create or replace function public.free_questions_remaining()
returns integer language plpgsql stable security definer set search_path=public as $$
declare uid uuid:=auth.uid(); p public.profiles%rowtype; used_n integer; daily_limit integer:=15;
begin
  if uid is null then raise exception 'No autenticado'; end if;
  select * into p from public.profiles where id=uid;
  if p.role in ('admin','moderator') or p.plan in ('pro','admin') then return -1; end if;
  select coalesce((value #>> '{}')::integer,15) into daily_limit
  from public.app_settings where key='free_daily_questions';
  select count(*)::integer into used_n from public.attempts
  where user_id=uid and selected_answer is not null
    and (answered_at at time zone 'America/Lima')::date=(now() at time zone 'America/Lima')::date;
  return greatest(0,coalesce(daily_limit,15)-used_n);
end; $$;

