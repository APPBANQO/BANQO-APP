create or replace function public.free_questions_remaining()
returns integer
language plpgsql
stable
security definer set search_path = public
as $$
declare
  uid uuid := auth.uid();
  p public.profiles%rowtype;
  used_n integer;
begin
  if uid is null then raise exception 'No autenticado'; end if;
  select * into p from public.profiles where id = uid;
  if p.role = 'admin' or p.plan in ('pro','admin') then return -1; end if;
  select count(*)::integer into used_n
  from public.attempts
  where user_id = uid
    and (answered_at at time zone 'America/Lima')::date = (now() at time zone 'America/Lima')::date;
  return greatest(0, 15 - used_n);
end;
$$;

create or replace function public.can_answer_today()
returns boolean
language sql
stable
security definer set search_path = public
as $$
  select public.free_questions_remaining() <> 0;
$$;

