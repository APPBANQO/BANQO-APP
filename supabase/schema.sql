create or replace view public.v_question_stats
with (security_invoker = true)
as
select
  q.id as question_id,
  q.external_id,
  count(a.id)::integer as attempts,
  count(a.id) filter (where a.is_correct is true)::integer as correct,
  case when count(a.id) = 0 then null
       else round(100.0 * count(a.id) filter (where a.is_correct is true) / count(a.id), 1)
  end as accuracy_pct
from public.questions q
left join public.attempts a on a.question_id = q.id
where q.status = 'PUBLICADA' or public.is_admin()
group by q.id, q.external_id;

-- ---------- progreso seguro del alumno ----------
-- Evita que un estudiante pueda editar directamente role/plan/xp/streak en profiles.
create or replace function public.award_session_progress(p_session_id uuid)
returns jsonb
language plpgsql
security definer set search_path = public
as $$
declare
  uid uuid := auth.uid();
  sess public.study_sessions%rowtype;
  correct_n integer := 0;
  gain integer := 0;
  new_xp integer;
  new_streak integer;
begin
  if uid is null then raise exception 'No autenticado'; end if;

  select * into sess
  from public.study_sessions
  where id = p_session_id and user_id = uid
  for update;

  if sess.id is null then raise exception 'Sesión no encontrada'; end if;
  if sess.status <> 'COMPLETADA' then raise exception 'La sesión no está completada'; end if;

  if sess.xp_awarded then
    select xp, streak into new_xp, new_streak from public.profiles where id = uid;
    return jsonb_build_object('ok', true, 'already_awarded', true, 'xp', new_xp, 'streak', new_streak, 'gain', 0);
  end if;

  select count(*)::integer into correct_n
  from public.attempts
  where session_id = p_session_id and user_id = uid and is_correct is true;

  gain := correct_n * 2 + 5;

  update public.profiles
  set xp = xp + gain, streak = streak + 1, updated_at = now()
  where id = uid
  returning xp, streak into new_xp, new_streak;

  update public.study_sessions set xp_awarded = true where id = p_session_id;

  return jsonb_build_object('ok', true, 'already_awarded', false, 'xp', new_xp, 'streak', new_streak, 'gain', gain);
end;
$$;

grant execute on function public.award_session_progress(uuid) to authenticated;

-- ---------- función para reclamar un dispositivo ----------
create or replace function public.claim_device(p_device_id text, p_device_name text default null)
returns jsonb
language plpgsql
security definer set search_path = public
as $$
declare
  current_row public.device_sessions%rowtype;
  uid uuid := auth.uid();
begin
  if uid is null then
    raise exception 'No autenticado';
  end if;

  select * into current_row from public.device_sessions where user_id = uid;

  if current_row.user_id is null then
    insert into public.device_sessions(user_id, device_id, device_name)
    values(uid, p_device_id, p_device_name);
    return jsonb_build_object('ok', true, 'claimed', true);
  end if;

  if current_row.device_id = p_device_id then
    update public.device_sessions
      set last_seen_at = now(), device_name = coalesce(p_device_name, device_name)
      where user_id = uid;
    return jsonb_build_object('ok', true, 'claimed', false);
  end if;

  -- Permite cambiar de dispositivo si el anterior lleva 12 h sin actividad.
  if current_row.last_seen_at < now() - interval '12 hours' then
    update public.device_sessions
      set device_id = p_device_id, device_name = p_device_name, last_seen_at = now()
      where user_id = uid;
    return jsonb_build_object('ok', true, 'claimed', true, 'replaced_stale', true);
  end if;

  return jsonb_build_object(
    'ok', false,
    'reason', 'OTHER_DEVICE_ACTIVE',
    'device_name', current_row.device_name,
    'last_seen_at', current_row.last_seen_at
  );
end;
$$;

grant execute on function public.claim_device(text,text) to authenticated;

