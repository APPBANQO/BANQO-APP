create or replace function public.start_practice(
  p_count integer, p_mode text, p_filters jsonb default '{}'::jsonb, p_random boolean default true,
  p_question_ids uuid[] default null
) returns jsonb language plpgsql security definer set search_path=public as $$
declare uid uuid:=auth.uid(); ids uuid[]; sid uuid; qs jsonb; allowed integer; requested integer;
begin
  if uid is null then raise exception 'No autenticado'; end if;
  requested:=greatest(1,least(coalesce(p_count,15),100)); allowed:=public.free_questions_remaining();
  if allowed=0 then raise exception 'FREE_LIMIT_REACHED' using errcode='P0001'; end if;
  if allowed>=0 then requested:=least(requested,allowed); end if;
  if p_mode not in ('instant','exam') then p_mode:='instant'; end if;

  if p_question_ids is not null then
    select array_agg(x.id order by array_position(p_question_ids,x.id)) into ids from (
      select id from public.questions where id=any(p_question_ids) and status='PUBLICADA'
      order by array_position(p_question_ids,id) limit requested
    ) x;
  elsif p_random then
    select array_agg(id) into ids from (
      select id from public.questions q where q.status='PUBLICADA'
      and (coalesce(p_filters->>'exam','')='' or q.exam_type=p_filters->>'exam')
      and (coalesce(p_filters->>'bank','')='' or q.bank_name=p_filters->>'bank')
      and (coalesce(p_filters->>'specialty','')='' or q.specialty=p_filters->>'specialty')
      and (coalesce(p_filters->>'topic','')='' or q.topic=p_filters->>'topic')
      and (coalesce(p_filters->>'subtopic','')='' or q.subtopic=p_filters->>'subtopic')
      order by random() limit requested
    ) x;
  else
    select array_agg(id) into ids from (
      select id from public.questions q where q.status='PUBLICADA'
      and (coalesce(p_filters->>'exam','')='' or q.exam_type=p_filters->>'exam')
      and (coalesce(p_filters->>'bank','')='' or q.bank_name=p_filters->>'bank')
      and (coalesce(p_filters->>'specialty','')='' or q.specialty=p_filters->>'specialty')
      and (coalesce(p_filters->>'topic','')='' or q.topic=p_filters->>'topic')
      and (coalesce(p_filters->>'subtopic','')='' or q.subtopic=p_filters->>'subtopic')
      order by q.external_id limit requested
    ) x;
  end if;
  if coalesce(array_length(ids,1),0)=0 then raise exception 'NO_QUESTIONS' using errcode='P0001'; end if;
  insert into public.study_sessions(user_id,session_type,filters,question_ids)
  values(uid,'PRACTICE',coalesce(p_filters,'{}'::jsonb)||jsonb_build_object('answer_mode',p_mode),ids)
  returning id into sid;
  select jsonb_agg(public.safe_question(q) order by array_position(ids,q.id)) into qs
  from public.questions q where q.id=any(ids);
  return jsonb_build_object('session_id',sid,'questions',coalesce(qs,'[]'::jsonb),'allowed',allowed);
end; $$;
grant execute on function public.start_practice(integer,text,jsonb,boolean,uuid[]) to authenticated;

create or replace function public.start_simulation(p_sim uuid,p_mode text default 'exam')
returns jsonb language plpgsql security definer set search_path=public as $$
declare uid uuid:=auth.uid(); sim public.simulation_sets%rowtype; ids uuid[]; sid uuid; qs jsonb; allowed integer;
begin
  if uid is null then raise exception 'No autenticado'; end if;
  select * into sim from public.simulation_sets where id=p_sim and status='PUBLICADO';
  if sim.id is null then raise exception 'SIMULATION_NOT_AVAILABLE' using errcode='P0001'; end if;
  select array_agg(sq.question_id order by sq.order_no) into ids
  from public.simulation_questions sq join public.questions q on q.id=sq.question_id
  where sq.simulation_id=p_sim and not sq.is_reserve and q.status='PUBLICADA';
  if coalesce(array_length(ids,1),0)<>sim.question_count then raise exception 'SIMULATION_NOT_READY' using errcode='P0001'; end if;
  allowed:=public.free_questions_remaining();
  if allowed>=0 and allowed<array_length(ids,1) then raise exception 'FREE_SIMULATION_LIMIT' using errcode='P0001'; end if;
  if p_mode not in ('instant','exam') then p_mode:='exam'; end if;
  insert into public.study_sessions(user_id,session_type,simulation_id,filters,question_ids)
  values(uid,'SIMULATION',sim.id,jsonb_build_object('name',sim.name,'answer_mode',p_mode),ids) returning id into sid;
  select jsonb_agg(public.safe_question(q) order by array_position(ids,q.id)) into qs
  from public.questions q where q.id=any(ids);
  return jsonb_build_object('session_id',sid,'simulation',to_jsonb(sim),'questions',qs);
end; $$;
grant execute on function public.start_simulation(uuid,text) to authenticated;

create or replace function public.resume_study_session(p_session uuid)
returns jsonb language plpgsql security definer set search_path=public as $$
declare uid uuid:=auth.uid(); s public.study_sessions%rowtype; qs jsonb; ans jsonb; st jsonb;
begin
  select * into s from public.study_sessions where id=p_session and user_id=uid;
  if s.id is null then raise exception 'Sesión no encontrada'; end if;
  if s.status='COMPLETADA' then
    select jsonb_agg(((to_jsonb(q)-array['review_notes','source_hash','created_by','updated_by'])||jsonb_build_object('explanation',case when q.explanation_source='AUTO_LOCAL' then '' else q.explanation end,'galactic_tip',case when q.explanation_source='AUTO_LOCAL' then '' else q.galactic_tip end)) order by array_position(s.question_ids,q.id)) into qs from public.questions q where q.id=any(s.question_ids);
  else
    select jsonb_agg(public.safe_question(q) order by array_position(s.question_ids,q.id)) into qs from public.questions q where q.id=any(s.question_ids);
  end if;
  select coalesce(jsonb_object_agg(question_id::text,selected_answer) filter(where selected_answer is not null),'{}'::jsonb) into ans
  from public.attempts where session_id=s.id and user_id=uid;
  select coalesce(jsonb_object_agg(question_id::text,jsonb_build_object('marked',marked,'discarded',discarded_options)),'{}'::jsonb) into st
  from public.study_question_state where session_id=s.id and user_id=uid;
  return jsonb_build_object('session',to_jsonb(s),'questions',coalesce(qs,'[]'::jsonb),'answers',ans,'question_state',st);
end; $$;
grant execute on function public.resume_study_session(uuid) to authenticated;

