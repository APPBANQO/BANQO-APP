create or replace function public.admin_update_user(p_user uuid,p_role text,p_plan text)
returns void language plpgsql security definer set search_path=public as $$
declare admin_count integer;
begin
  if not public.is_admin() then raise exception 'No autorizado' using errcode='42501'; end if;
  if p_role not in ('student','moderator','admin') or p_plan not in ('free','pro','admin') then raise exception 'Valor inválido'; end if;
  if exists(select 1 from public.profiles where id=p_user and role='admin') and p_role<>'admin' then
    select count(*) into admin_count from public.profiles where role='admin';
    if admin_count<=1 then raise exception 'No puedes quitar el rol al último administrador'; end if;
  end if;
  update public.profiles set role=p_role,plan=p_plan where id=p_user;
end; $$;
grant execute on function public.admin_update_user(uuid,text,text) to authenticated;

