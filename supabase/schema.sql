create or replace function public.answer_question(
  p_session uuid,p_question uuid,p_letter text,p_marked boolean default false,
  p_discarded text[] default '{}'::text[],p_response_ms integer default null
) returns jsonb language plpgsql security definer set search_path=public as $$
declare uid uuid:=auth.uid(); s public.study_sessions%rowtype; q public.questions%rowtype; ok boolean; mode text; remaining integer;
begin
  if uid is null then raise exception 'No autenticado'; end if;
  perform pg_advisory_xact_lock(hashtext(uid::text));
  select * into s from public.study_sessions where id=p_session and user_id=uid and status='EN_CURSO' for update;
  if s.id is null or not p_question=any(s.question_ids) then raise exception 'Sesión no válida' using errcode='42501'; end if;
  if upper(p_letter) not in ('A','B','C','D','E') then raise exception 'Respuesta no válida'; end if;
  if not exists(select 1 from public.attempts where session_id=p_session and question_id=p_question and selected_answer is not null) then
    remaining:=public.free_questions_remaining();
    if remaining=0 then raise exception 'FREE_LIMIT_REACHED' using errcode='P0001'; end if;
  end if;
  select * into q from public.questions where id=p_question;
  ok:=upper(p_letter)=q.correct_answer; mode:=coalesce(s.filters->>'answer_mode','instant');
  insert into public.attempts(session_id,user_id,question_id,selected_answer,is_correct,marked,discarded_options,response_ms,answered_at)
  values(p_session,uid,p_question,upper(p_letter),ok,coalesce(p_marked,false),coalesce(p_discarded,'{}'::text[]),greatest(0,p_response_ms),now())
  on conflict(session_id,question_id) do update set selected_answer=excluded.selected_answer,is_correct=excluded.is_correct,
    marked=excluded.marked,discarded_options=excluded.discarded_options,response_ms=excluded.response_ms,answered_at=now();
  perform public.save_question_state(p_session,p_question,p_marked,p_discarded);
  if mode='instant' then
    return jsonb_build_object('ok',true,'is_correct',ok,'correct_answer',q.correct_answer,
      'explanation',case when q.explanation_source='AUTO_LOCAL' then '' else q.explanation end,
      'galactic_tip',case when q.explanation_source='AUTO_LOCAL' then '' else q.galactic_tip end);
  end if;
  return jsonb_build_object('ok',true);
end; $$;
grant execute on function public.answer_question(uuid,uuid,text,boolean,text[],integer) to authenticated;

create or replace function public.complete_study_session(p_session uuid,p_elapsed integer default 0)
returns jsonb language plpgsql security definer set search_path=public as $$
declare uid uuid:=auth.uid(); s public.study_sessions%rowtype; total integer; correct_n integer; incorrect_n integer; blank_n integer; score_n numeric; qs jsonb;
begin
  select * into s from public.study_sessions where id=p_session and user_id=uid for update;
  if s.id is null then raise exception 'Sesión no encontrada' using errcode='42501'; end if;
  total:=coalesce(array_length(s.question_ids,1),0);
  select count(*) filter(where is_correct is true),count(*) filter(where selected_answer is not null and is_correct is false)
    into correct_n,incorrect_n from public.attempts where session_id=s.id and user_id=uid;
  blank_n:=greatest(0,total-correct_n-incorrect_n); score_n:=case when total=0 then 0 else round(correct_n*100.0/total,2) end;
  update public.study_sessions set status='COMPLETADA',correct_count=correct_n,incorrect_count=incorrect_n,
    blank_count=blank_n,score=score_n,elapsed_seconds=greatest(0,p_elapsed),finished_at=coalesce(finished_at,now()) where id=s.id;
  select jsonb_agg(((to_jsonb(q)-array['review_notes','source_hash','created_by','updated_by'])||jsonb_build_object('explanation',case when q.explanation_source='AUTO_LOCAL' then '' else q.explanation end,
    'galactic_tip',case when q.explanation_source='AUTO_LOCAL' then '' else q.galactic_tip end)) order by array_position(s.question_ids,q.id))
    into qs from public.questions q where q.id=any(s.question_ids);
  return jsonb_build_object('correct',correct_n,'incorrect',incorrect_n,'blank',blank_n,'score',score_n,'questions',coalesce(qs,'[]'::jsonb));
end; $$;
grant execute on function public.complete_study_session(uuid,integer) to authenticated;

